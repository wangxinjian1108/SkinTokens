"""The 22-joint target skeleton used by LaFAN1 BVH motion files.

Names and hierarchy follow the Mixamo/CMU convention that LaFAN1 uses, so the
post-processed rig can be mapped 1:1 onto a LaFAN1 BVH skeleton by name.
"""

from __future__ import annotations

# Canonical order (parents always appear before their children).
LAFAN1_JOINTS: list[str] = [
    "Hips",
    "Spine",
    "Spine1",
    "Spine2",
    "Neck",
    "Head",
    "LeftShoulder",
    "LeftArm",
    "LeftForeArm",
    "LeftHand",
    "RightShoulder",
    "RightArm",
    "RightForeArm",
    "RightHand",
    "LeftUpLeg",
    "LeftLeg",
    "LeftFoot",
    "LeftToe",
    "RightUpLeg",
    "RightLeg",
    "RightFoot",
    "RightToe",
]

LAFAN1_PARENTS: dict[str, str | None] = {
    "Hips": None,
    "Spine": "Hips",
    "Spine1": "Spine",
    "Spine2": "Spine1",
    "Neck": "Spine2",
    "Head": "Neck",
    "LeftShoulder": "Spine2",
    "LeftArm": "LeftShoulder",
    "LeftForeArm": "LeftArm",
    "LeftHand": "LeftForeArm",
    "RightShoulder": "Spine2",
    "RightArm": "RightShoulder",
    "RightForeArm": "RightArm",
    "RightHand": "RightForeArm",
    "LeftUpLeg": "Hips",
    "LeftLeg": "LeftUpLeg",
    "LeftFoot": "LeftLeg",
    "LeftToe": "LeftFoot",
    "RightUpLeg": "Hips",
    "RightLeg": "RightUpLeg",
    "RightFoot": "RightLeg",
    "RightToe": "RightFoot",
}

assert len(LAFAN1_JOINTS) == 22
assert set(LAFAN1_PARENTS) == set(LAFAN1_JOINTS)


def is_finger(label: str) -> bool:
    return "HandFinger" in label
